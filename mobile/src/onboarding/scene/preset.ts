export const IDENTITY: Transform = {
  x: 0,
  y: 0,
  scaleX: 1,
  scaleY: 1,
  rotation: 0,
  anchorX: 0,
  anchorY: 0,
  opacity: 1,
};

function obj(
  id: string,
  name: string,
  at: Partial<Transform>,
  body: Body,
  motion: Motion | null = null,
): SceneObject {
  return {
    id,
    name,
    transform: { ...IDENTITY, ...at },
    stroke: '$ravine',
    strokeWidth: 0,
    motion,
    body,
  };
}

function layer(id: LayerId, name: string, parallax: number, objects: SceneObject[]): Layer {
  return {
    id,
    name,
    visible: true,
    locked: false,
    parallax,
    opacity: 1,
    blur: 0,
    objects,
  };
}

const pts = (...xy: number[]): Vec[] => {
  const out: Vec[] = [];
  for (let i = 0; i < xy.length; i += 2) out.push({ x: xy[i], y: xy[i + 1] });
  return out;
};

const drift = (amplitude: number, period: number, delay = 0): Motion => ({
  kind: 'drift',
  amplitude,
  period,
  delay,
});
const sway = (amplitude: number, period: number, delay = 0): Motion => ({
  kind: 'sway',
  amplitude,
  period,
  delay,
});

/** Keys at screens 1, 2, 3 (progress 0, 1, 2). */
const track = (target: string, ...values: Keyframe['value'][]): Track => ({
  target,
  easing: 'linear',
  keys: values.map((value, at) => ({ at, value })),
});

