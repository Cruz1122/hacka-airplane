def build_round3(entry) -> list[dict]:
    made = []
    for item in ROWS:
        if len(item["short"]) > 320:
            raise ValueError(f"{item['suffix']} short {len(item['short'])}")
        made.append(
            entry(
                item["suffix"],
                item["label"],
                item["kind"],
                item["examples"],
                item["short"],
                item["variants"],
                item["sources"],
                NEGATIVES,
                item["related"],
                item["tags"],
            )
        )
    return made


