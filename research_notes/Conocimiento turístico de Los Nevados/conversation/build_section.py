def entry(eid, label, kind, examples, short, hard_negatives, related, tags,
          sources=None, variants=None, last_verified=None):
    e = {
        "id": f"conversation.{eid}",
        "label": label,
        "kind": kind,
        "audience": "visitor",
        "examples": examples,
        "hard_negatives": hard_negatives,
        "answer": {"short": short},
        "sources": sources or [EDITORIAL],
        "related": [r if r.startswith("conversation.") else f"conversation.{r}" for r in related],
        "tags": tags,
    }
    if variants:
        e["answer"]["variants"] = variants
    if last_verified:
        e["last_verified"] = last_verified
    return e


