def row(
    suffix: str,
    label: str,
    kind: str,
    examples: list[str],
    short: str,
    variant: str,
    sources: list[dict[str, str]],
    related: list[str],
    tags: list[str],
) -> dict:
    # Each example list is written by hand. Do not rebuild it from a shared pattern.
    if len(label.split()) < 3 or len(label.split()) > 8:
        raise ValueError(f"label words: {label}")
    if len(examples) < 12 or len(set(examples)) != len(examples):
        raise ValueError(f"examples: {suffix} {len(examples)}")
    if len(short) > 320:
        raise ValueError(f"{suffix} short {len(short)}")
    return {
        "suffix": suffix,
        "label": label,
        "kind": kind,
        "examples": examples,
        "short": short,
        "variants": [variant],
        "sources": sources,
        "related": related,
        "tags": tags,
    }


